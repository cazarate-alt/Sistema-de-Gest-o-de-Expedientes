DELIMITER $$
CREATE TRIGGER `TRG_DOCUMENT_VALIDATE_STATUS` BEFORE UPDATE ON `DOCUMENT` FOR EACH ROW
BEGIN
    IF NEW.DOCUMENT_STATUS IN ('RESOLVED','CLOSED')
       AND OLD.DOCUMENT_STATUS NOT IN ('RESOLVED','CLOSED') THEN
        IF @app_profile_code IS NOT NULL
           AND @app_profile_code NOT IN ('SECR','SUPE') THEN
            SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Apenas a Secretaria pode entregar documentos ao Estudante.';
        END IF;
    END IF;

    IF NEW.DOCUMENT_STATUS = 'REJECTED'
       AND OLD.DOCUMENT_STATUS <> 'REJECTED' THEN
        IF @app_profile_code IS NOT NULL
           AND @app_profile_code NOT IN ('DIRE','SUPE') THEN
            SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Apenas o Director pode rejeitar documentos.';
        END IF;
    END IF;
END$$
