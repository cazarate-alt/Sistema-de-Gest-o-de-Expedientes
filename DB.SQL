CREATE TRIGGER `TRG_SESSION_INSERT` AFTER INSERT ON `SESSION` FOR EACH ROW
BEGIN
    DECLARE v_user VARCHAR(200);
    SELECT CONCAT(USER_CODE,' - ',USER_FIRSTNAME,' ',USER_LASTNAME) INTO v_user
      FROM `USERS` WHERE USER_ID = NEW.USER_ID;
    INSERT INTO `LOG` (LOG_USER_ID, LOG_USER_NAME, LOG_MODULE, LOG_ACTION,
                       LOG_TYPE, LOG_DESCRIPTION, LOG_IP, LOG_USER_AGENT)
    VALUES (NEW.USER_ID, v_user, 'SESSION','LOGIN','SECURITY',
            CONCAT('Sessão iniciada. SESSION_ID=', NEW.SESSION_ID),
            NEW.SESSION_IP, NEW.SESSION_USER_AGENT);
END$$
DELIMITER ;

DROP TRIGGER IF EXISTS `TRG_SESSION_UPDATE`;
DELIMITER $$
CREATE TRIGGER `TRG_SESSION_UPDATE` AFTER UPDATE ON `SESSION` FOR EACH ROW
BEGIN
    DECLARE v_user VARCHAR(200);
    IF OLD.SESSION_STATUS <> NEW.SESSION_STATUS
       AND NEW.SESSION_STATUS IN ('EXPIRED','LOGGED_OUT') THEN
        SELECT CONCAT(USER_CODE,' - ',USER_FIRSTNAME,' ',USER_LASTNAME) INTO v_user
          FROM `USERS` WHERE USER_ID = NEW.USER_ID;
        INSERT INTO `LOG` (LOG_USER_ID, LOG_USER_NAME, LOG_MODULE, LOG_ACTION,
                           LOG_TYPE, LOG_DESCRIPTION, LOG_IP, LOG_USER_AGENT)
        VALUES (NEW.USER_ID, v_user, 'SESSION',
                IF(NEW.SESSION_STATUS='LOGGED_OUT','LOGOUT','EXPIRED'),
                'SECURITY',
                CONCAT('Sessão terminada (',NEW.SESSION_STATUS,'). SESSION_ID=',NEW.SESSION_ID),
                NEW.SESSION_IP, NEW.SESSION_USER_AGENT);
    END IF;
END$$
