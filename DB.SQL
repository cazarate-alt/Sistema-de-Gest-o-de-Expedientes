DROP PROCEDURE IF EXISTS `SP_SET_APP_CONTEXT`;
DELIMITER $$
CREATE PROCEDURE `SP_SET_APP_CONTEXT`(
    IN p_user_id INT,
    IN p_user_name VARCHAR(200),
    IN p_profile_code VARCHAR(30),
    IN p_ip VARCHAR(45),
    IN p_user_agent VARCHAR(500)
)
BEGIN
    SET @app_user_id      = p_user_id;
    SET @app_user_name    = p_user_name;
    SET @app_profile_code = p_profile_code;
    SET @app_user_ip      = p_ip;
    SET @app_user_agent   = p_user_agent;
END$$
DELIMITER ;

DROP PROCEDURE IF EXISTS `SP_WRITE_LOG`;
DELIMITER $$
CREATE PROCEDURE `SP_WRITE_LOG`(
    IN p_module VARCHAR(100),
    IN p_action VARCHAR(100),
    IN p_type VARCHAR(20),
    IN p_description TEXT
)
BEGIN
    INSERT INTO `LOG` (LOG_USER_ID, LOG_USER_NAME, LOG_MODULE, LOG_ACTION,
                       LOG_TYPE, LOG_DESCRIPTION, LOG_IP, LOG_USER_AGENT)
    VALUES (@app_user_id, @app_user_name, p_module, p_action, p_type,
            p_description, @app_user_ip, @app_user_agent);
END$$
